export function calcularAlertaVencimientoUI(
  ruc: string,
  periodo: string,
  fechaHoy?: string
): AlertaVencimientoUI {
  const digito = (ruc && ruc.trim().length > 0) ? ruc.trim().slice(-1) : '0';
  const perKey = (periodo && periodo.includes('-')) ? periodo.slice(0, 7) : '2026-09';
  
  let fechaVenc = CRONOGRAMA_SUNAT_2026[perKey]?.[digito];
  if (!fechaVenc) {
    // Cálculo supletorio si no está en tabla 2026: mes siguiente día 15 + digito
    const [anioStr, mesStr] = perKey.split('-');
    const a = parseInt(anioStr, 10) || 2026;
    const m = parseInt(mesStr, 10) || 1;
    const anioV = m === 12 ? a + 1 : a;
    const mesV = m === 12 ? 1 : m + 1;
    const diaV = Math.min(28, 15 + (parseInt(digito, 10) || 0));
    fechaVenc = `${anioV}-${String(mesV).padStart(2, '0')}-${String(diaV).padStart(2, '0')}`;
  }

  const hoyStr = fechaHoy || new Date().toISOString().slice(0, 10);
  const msPorDia = 1000 * 60 * 60 * 24;
  const tHoy = new Date(`${hoyStr}T00:00:00Z`).getTime();
  const tVenc = new Date(`${fechaVenc}T00:00:00Z`).getTime();
  const diasRestantes = Math.round((tVenc - tHoy) / msPorDia);

  const esVencido = diasRestantes < 0;
  let etiquetaDias = '';
  if (diasRestantes < 0) {
    etiquetaDias = `Vencido hace ${Math.abs(diasRestantes)} d`;
  } else if (diasRestantes === 0) {
    etiquetaDias = 'Vence hoy';
  } else {
    etiquetaDias = `${diasRestantes} días`;
  }

  return {
    periodo: perKey,
    digito,
    fechaVencimiento: fechaVenc,
    diasRestantes,
    esVencido,
    etiquetaDias
  };
}

